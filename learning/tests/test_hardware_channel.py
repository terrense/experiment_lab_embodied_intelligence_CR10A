"""Tests for the hardware command-channel measurement (SIMULATION ONLY until a real capture exists).

The on-site capture (`ros2_ws/src/ex_dobot_motion/ex_dobot_motion/channel.py`) and its offline
analysis (`evaluation/measure_execution_hardware.py`) are the paper's missing hardware piece: the
command channel has only ever been measured on the simulator, and the whole "execution-aware"
argument transfers to hardware only if the real channel behaves like that.

These tests verify BOTH halves without a robot:
  * the capture's PLAN is a pure function, so its safety properties are checked directly - the
    step size is bounded, the joint index is checked, and the plan is validated against the same
    safety envelope the excitation runner uses;
  * the ANALYSIS is tested on a SYNTHETIC capture generated from the simulator's own model, so
    the fitting and the residual-motion measurement are verified before they ever see the real
    arm. A fitting that cannot recover a known model would not be trusted with a real one.
"""

