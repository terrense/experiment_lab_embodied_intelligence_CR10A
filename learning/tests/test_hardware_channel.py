# ------------------------------------------------------------------ the capture's plan
def test_the_step_plan_is_bounded_and_checked():
    from ex_dobot_motion.channel import make_step_plan
    q0 = [0.0, -20.0, 90.0, 0.0, -90.0, 0.0]
    plan = make_step_plan(q0, joint=5, step_deg=4.0)
    assert plan["joint"] == 5
    assert plan["waypoints_deg"][0][4] == pytest.approx(q0[4] + 4.0)
    assert plan["waypoints_deg"][1] == pytest.approx(list(q0))   # and back
    # the other joints are untouched
    for i in range(6):
        if i != 4:
            assert plan["waypoints_deg"][0][i] == pytest.approx(q0[i])


def test_the_step_size_and_the_joint_are_bounded():
    from ex_dobot_motion.channel import make_step_plan
    q0 = [0.0] * 6
    with pytest.raises(ValueError):
        make_step_plan(q0, joint=0, step_deg=4.0)          # no joint 0
    with pytest.raises(ValueError):
        make_step_plan(q0, joint=7, step_deg=4.0)          # no joint 7
    with pytest.raises(ValueError):
        make_step_plan(q0, joint=5, step_deg=0.01)         # too small to measure
    with pytest.raises(ValueError):
        make_step_plan(q0, joint=5, step_deg=90.0)         # too big to be safe


def test_the_step_plan_is_validated_against_the_safety_envelope():
    """A step that would put a joint near its limit must be refused."""
    from ex_dobot_motion.channel import make_step_plan, validate_step_plan
    from ex_dobot_motion.excitation import SafetyEnvelope

    lower = [-180.0, -120.0, -150.0, -180.0, -180.0, -360.0]
    upper = [180.0, 120.0, 150.0, 180.0, 180.0, 360.0]

    def positions(q_deg):
        # a stand-in geometry: the TCP is 0.5 m up and 0.4 m out
        return {"tcp": np.array([0.4, 0.0, 0.5]),
                "Link3": np.array([0.3, 0.0, 0.4]), "Link4": np.array([0.3, 0.0, 0.4]),
                "Link5": np.array([0.2, 0.0, 0.3]), "Link6": np.array([0.2, 0.0, 0.3])}

    # a comfortable pose: OK
    plan = make_step_plan([0.0, -20.0, 90.0, 0.0, -90.0, 0.0], joint=5, step_deg=4.0)
    assert validate_step_plan(plan, positions, lower, upper, SafetyEnvelope()) == []

    # a pose with J5 already near its limit: the step must be refused
    near = [0.0, -20.0, 90.0, 0.0, 179.0, 0.0]
    plan2 = make_step_plan(near, joint=5, step_deg=4.0)
    problems = validate_step_plan(plan2, positions, lower, upper, SafetyEnvelope())
    assert problems, "a step that crosses the joint-limit margin must be refused"


# ------------------------------------------------------------- the analysis, on synthetic data
def _synthetic_capture(path: Path, omega: float = 37.7, zeta: float = 0.9,
                        v_gain: float = 0.8, step_rad: float = 0.07, dt: float = 0.008,
                        settle_s: float = 2.0) -> None:
    """A step response generated by the simulator's own model, in the capture's CSV format."""
    m = ServoExecutionModel(omega=omega, zeta=zeta, v_gain=v_gain, dt=dt, sub=1)
    n = int((0.4 + settle_s) / dt)
    # A position interface does NOT step its target: it RAMPS it (the controller interpolates).
    # The synthetic capture therefore ramps the target over `ramp_s` and then holds - which is
    # what the real arm's `q_target` looks like, and what makes the residual-motion measurement
    # meaningful (the instant the ramp ends is the instant the command stops changing).
    # The ramp has to be FAST relative to the servo: the closed loop settles in 2*zeta/omega =
    # 48 ms, so a ramp of a few tens of milliseconds is what makes the parameters identifiable.
    # A slow ramp (the controller's own interpolation is slow) lets many parameter sets reproduce
    # the response equally well - a finding the on-site procedure has to respect, because the
    # excitation is what the operator controls.
    t_start, ramp_s = 0.2, 0.03

    def target(t):
        if t <= t_start:
            return 0.0
        if t >= t_start + ramp_s:
            return step_rad
        return step_rad * (t - t_start) / ramp_s

    q, qd = 0.0, 0.0
    rows = []
    for i in range(n):
        t = i * dt
        # a ZERO-ORDER HOLD on the target, exactly as the analysis assumes: the plant sees the
        # PREVIOUS sample's target and the target's rate over the last interval
        qt = target(t)
        qt_prev = target(t - dt)
        v_ref = (qt - qt_prev) / dt
        qdd = m.omega ** 2 * (qt_prev - q) + 2 * m.zeta * m.omega * (m.v_gain * v_ref - qd)
        qd += qdd * dt
        q += qd * dt
        rows.append([t, int(t * 1000), 5, 1, 0, 0]
                    + [0.0] * 6 + [qd] + [0.0] * 6 + [0.0] * 6 + [0.0] * 6 + [0, 0, 0, 0, 0, 0])
    with path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(CAPTURE_COLUMNS)
        for r in rows:
            w.writerow(r)
    # rewrite the J5 columns: the measured position, the velocity and the commanded target
    with path.open(newline="") as f:
        rr = list(csv.reader(f))
    header, data = rr[0], rr[1:]
    q, qd = 0.0, 0.0
    for i, r in enumerate(data):
        t = i * dt
        qt = target(t)
        qt_prev = target(t - dt)
        v_ref = (qt - qt_prev) / dt
        qdd = m.omega ** 2 * (qt_prev - q) + 2 * m.zeta * m.omega * (m.v_gain * v_ref - qd)
        qd += qdd * dt
        q += qd * dt
        r[header.index("q5_deg")] = math.degrees(q)
        r[header.index("qd5")] = qd
        r[header.index("qt5_deg")] = math.degrees(qt)
    with path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        for r in data:
            w.writerow(r)


def test_the_analysis_recovers_a_known_channel(tmp_path):
    """A fitting that cannot recover a KNOWN model must not be trusted with the real arm."""
    from measure_execution_hardware import analyse

    cap = tmp_path / "channel.csv"
    _synthetic_capture(cap, omega=37.7, zeta=0.9, v_gain=0.8)
    rep = analyse(cap, joint=5)
    model = rep["identification"]["model"]
    assert model["omega"] == pytest.approx(37.7, rel=0.20)
    assert model["zeta"] == pytest.approx(0.9, rel=0.25)
    assert rep["identification"]["prediction_error"]["rms_rad"] < 0.01
    # the tracking lag is measured DIRECTLY, so it does not depend on the model being identifiable
    assert rep["tracking_lag"]["response_delay_s"] is not None
    assert rep["tracking_lag"]["response_delay_s"] > 0.0
    assert rep["tracking_lag"]["correlation"] > 0.5


def test_the_residual_motion_is_measured(tmp_path):
    """The residual motion is the hardware counterpart of the simulator's coast."""
    from measure_execution_hardware import analyse

    cap = tmp_path / "channel.csv"
    _synthetic_capture(cap, omega=37.7, zeta=0.9, v_gain=0.8, step_rad=0.07)
    rep = analyse(cap, joint=5)
    coast = rep["coast"]
    assert "error" not in coast, coast
    assert coast["residual_travel_rad"] > 0.0
    assert coast["speed_at_cut_rad_s"] > 0.0
    assert coast["settle_s"] is not None and coast["settle_s"] >= 0.0
    assert coast["residual_travel_mrad"] > 0.0


