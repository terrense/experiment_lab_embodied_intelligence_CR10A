def test_the_comparison_with_the_simulator_uses_the_same_schema(tmp_path):
    """The two channels have to be comparable numbers, not two vocabularies."""
    import measure_execution_hardware as mh

    sim = ROOT / "data" / "reports" / "learning" / "execution_channel.json"
    assert sim.exists(), "the simulator's channel measurement must be committed"
    blob = json.loads(sim.read_text())
    assert "identification" in blob and "model" in blob["identification"]
    hw = {"identification": {"model": {"omega": 30.0, "zeta": 1.0, "v_gain": 0.9},
                              "prediction_error": {"rms_rad": 0.01}},
          "coast": {"residual_travel_rad": 0.02}}
    cmp = mh.compare_with_simulator(hw, sim)
    assert cmp["ratio_omega"] == pytest.approx(30.0 / blob["identification"]["model"]["omega"])
    assert "coast_ratio" in cmp
