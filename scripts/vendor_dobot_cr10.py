#!/usr/bin/env python3
"""Derive ex_description's CR10 macro from the pinned official Dobot xacro.

Reproducible: same input commit -> byte-identical output. What it changes:
  * drops <gazebo>, <ros2_control> (they need cr10_moveit at xacro time)
  * drops official world / dummy_link / world_joint / dummy_joint (we define
    the world->base mounting explicitly in ex_cr10.urdf.xacro)
  * rewrites mesh URIs to package://ex_description/meshes/cr10_official/
  * copies the 7 STL meshes verbatim and the upstream MIT LICENSE
Kinematic numbers (origins, axes, limits) are copied unmodified.

usage: python3 scripts/vendor_dobot_cr10.py [third_party/dobot_main]
"""

from __future__ import annotations

import hashlib
import re
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "third_party" / "dobot_main"
PKG = ROOT / "ros2_ws" / "src" / "ex_description"
UPSTREAM_COMMIT = "ec201c40d5db63185a3593ec9c39f80fe25aa527"
# Joint-limit overlay for the CR10A (rad, symmetric). Geometry is NOT changed.
# Evidence (docs/HARDWARE_COMPATIBILITY.md §2): CR10A spec J1/2/4/5/6 +-360 deg,
# J3 +-160 deg (retailer datasheets); official TCP-IP-ROS-6AXis cr10 URDF uses
# J3 +-2.793 rad (=160.0 deg), while the V4 repo cr10 URDF says +-2.861 (163.9 deg).
LIMIT_OVERLAY = {"joint1": 6.2832, "joint2": 6.2832, "joint3": 2.7925,
                 "joint4": 6.2832, "joint5": 6.2832, "joint6": 6.2832}
DROP_TAGS = {"gazebo", "ros2_control"}
DROP_NAMES = {"world", "dummy_link", "world_joint", "dummy_joint"}


def main() -> None:
    xacro = SRC / "cra_description" / "urdf" / "cr10_robot.xacro"
    text = xacro.read_text(encoding="utf-8")
    src_sha = hashlib.sha256(text.encode()).hexdigest()
    root = ET.fromstring(text)
    body = []
    overlay_log: list[str] = []
    for el in list(root):
        if el.tag in DROP_TAGS or el.get("name") in DROP_NAMES:
            continue
        for mesh in el.iter("mesh"):
            fn = mesh.get("filename")
            m = re.search(r"meshes/cr10/([\w.]+)$", fn)
            if not m:
                raise SystemExit(f"unexpected mesh path {fn}")
            mesh.set("filename", f"package://ex_description/meshes/cr10_official/{m.group(1)}")
        for mat in el.iter("material"):  # upstream uses name="" which is invalid to share
            mat.set("name", "")
        if el.tag == "joint" and el.get("name") in LIMIT_OVERLAY:
            lim = el.find("limit")
            orig = (lim.get("lower"), lim.get("upper"))
            v = LIMIT_OVERLAY[el.get("name")]
            lim.set("lower", f"{-v}")
            lim.set("upper", f"{v}")
            overlay_log.append(f"    {el.get('name')}: upstream [{orig[0]}, {orig[1]}] -> [-{v}, {v}]")
        ET.indent(el, space="  ", level=1)
        body.append("  " + ET.tostring(el, encoding="unicode").strip())

    joints = [e for e in root if e.tag == "joint" and e.get("type") != "fixed"]
    assert [j.get("name") for j in joints] == [f"joint{i}" for i in range(1, 7)], "joint naming changed upstream"

    out = PKG / "urdf" / "dobot_cr10_official.xacro"
    out.parent.mkdir(parents=True, exist_ok=True)
    header = f"""<?xml version="1.0"?>
<!--
  GENERATED by scripts/vendor_dobot_cr10.py - do not edit by hand.
  Source : Dobot-Arm/DOBOT_6Axis_ROS2_V4 @ {UPSTREAM_COMMIT}
           cra_description/urdf/cr10_robot.xacro (sha256 {src_sha[:16]}...)
  License: MIT (c) 2026 Dobot - see meshes/cr10_official/LICENSE.dobot
  Model  : official cr10 geometry from the V4 (CRA-series) repo; identical
           geometry in DOBOT_6Axis_ROS2_V3 and TCP-IP-ROS-6AXis. Match to the
           physical CR10A is UNVERIFIED until the on-site FK cross-check
           (docs/HARDWARE_COMPATIBILITY.md). Visualisation / offline only.
  Joint-limit overlay (CR10A datasheet), geometry unchanged:
{chr(10).join(overlay_log)}
-->
<robot xmlns:xacro="http://www.ros.org/wiki/xacro">
<xacro:macro name="dobot_cr10_official">
"""
    out.write_text(header + "\n".join(body) + "\n</xacro:macro>\n</robot>\n", encoding="utf-8")

    mdst = PKG / "meshes" / "cr10_official"
    mdst.mkdir(parents=True, exist_ok=True)
    for stl in sorted((SRC / "cra_description" / "meshes" / "cr10").glob("*.STL")):
        shutil.copy2(stl, mdst / stl.name)
    shutil.copy2(SRC / "LICENSE", mdst / "LICENSE.dobot")
    print(f"wrote {out.relative_to(ROOT)} and {len(list(mdst.glob('*.STL')))} meshes")


if __name__ == "__main__":
    main()
